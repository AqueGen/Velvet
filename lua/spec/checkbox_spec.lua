local helper = require("spec.helper")

describe("UI.Checkbox", function()
  local UI, box
  before_each(function()
    UI = helper.load()
    box = UI.Checkbox(UIParent)
  end)

  it("is a 22x22 CheckButton with a flat well and a control edge", function()
    assert.equal("CheckButton", box:GetObjectType())
    assert.equal(22, box:GetWidth())
    assert.is_true(helper.near(UI.T.well, box.backdropColor))
    assert.is_true(helper.near(UI.T.control, box.backdropBorder))
    assert.is_false(box.check:IsShown())
  end)

  it("takes a custom size", function()
    assert.equal(16, UI.Checkbox(UIParent, 16):GetHeight())
  end)

  it("paints the checked state from SetChecked and back", function()
    box:SetChecked(true)
    assert.is_true(box:GetChecked())
    assert.is_true(box.check:IsShown())
    assert.is_true(helper.near(UI.T.wellOn, box.backdropColor))
    assert.is_true(helper.near(UI.T.trackFill, box.backdropBorder))
    assert.is_true(box.check.desaturated)
    assert.is_true(helper.near(UI.T.tick, box.check.vertex))
    box:SetChecked(false)
    assert.is_false(box.check:IsShown())
    assert.is_true(helper.near(UI.T.well, box.backdropColor))
  end)

  it("repaints after a click and still runs the caller's OnClick", function()
    local seen
    box:SetScript("OnClick", function(self) seen = self:GetChecked() end)
    box:Click()
    assert.is_true(seen)
    assert.is_true(box.check:IsShown())
  end)

  it("greys out only its own art and ignores clicks while disabled", function()
    local label = box:CreateFontString(nil, "OVERLAY")
    box:Disable()
    box:Click()
    assert.is_falsy(box:GetChecked())
    assert.equal(1, box:GetAlpha())
    assert.equal(1, label:GetAlpha())
    assert.equal(0.45, box.check:GetAlpha())
    assert.equal(0.45, box.backdropBorder[4])
    box:Enable()
    assert.equal(1, box.check:GetAlpha())
    assert.equal(1, box.backdropBorder[4])
    box:SetChecked(true)
    box:SetEnabled(false)
    assert.equal(0.45, box.backdropColor[4])
  end)
end)
