local helper = require("spec.helper")

describe("UI.Slider", function()
  local UI, slider, changes
  before_each(function()
    UI = helper.load()
    changes = {}
    slider = UI.Slider(UIParent, 220)
    slider.onChange = function(value) changes[#changes + 1] = value end
  end)

  it("is 22 high with flat track, fill and thumb in the token colours", function()
    assert.equal(220, slider:GetWidth())
    assert.equal(22, slider:GetHeight())
    assert.equal(4, slider.track:GetHeight())
    assert.is_true(helper.near(UI.T.track, slider.track.color))
    assert.is_true(helper.near(UI.T.trackFill, slider.fill.color))
    assert.is_true(helper.near(UI.T.thumb, slider.thumb.color))
    assert.equal("-", slider.down.label:GetText())
    assert.equal("+", slider.up.label:GetText())
  end)

  it("lands on exact float steps after repeated + clicks", function()
    slider:Setup(0.5, 2, 0.05)
    slider:SetValue(1, true)
    for _ = 1, 10 do slider.up:Click() end
    assert.equal(1.5, slider:GetValue())
    assert.equal(10, #changes)
    assert.equal(1.5, changes[10])
  end)

  it("clamps an out-of-range saved value without reporting it", function()
    slider:Setup(3, 60, 1)
    slider:SetValue(70, true)
    assert.equal(60, slider:GetValue())
    assert.same({}, changes)
  end)

  it("reports a value set without silent once", function()
    slider:Setup(3, 60, 1)
    slider:SetValue(7)
    assert.same({ 7 }, changes)
  end)

  it("reports a drag on the widget through onChange, snapped", function()
    slider:Setup(0, 15, 1)
    slider.widget:SetValue(4.4)
    assert.equal(4, slider:GetValue())
    assert.same({ 4 }, changes)
  end)

  it("ignores steppers while disabled and greys out", function()
    slider:Setup(3, 60, 1)
    slider:SetValue(10, true)
    slider:SetEnabled(false)
    slider.up:Click()
    assert.equal(10, slider:GetValue())
    assert.same({}, changes)
    assert.equal(0.45, slider.thumb:GetAlpha())
    assert.is_false(slider.widget:IsEnabled())
    slider:SetEnabled(true)
    slider.up:Click()
    assert.equal(11, slider:GetValue())
  end)

  it("fills nothing at the minimum and the whole track at the maximum", function()
    slider:Setup(0, 15, 1)
    slider:SetValue(0, true)
    assert.is_true(slider.fill:GetWidth() < 0.01)
    slider:SetValue(15, true)
    assert.equal(slider.track:GetWidth(), slider.fill:GetWidth())
  end)
end)
